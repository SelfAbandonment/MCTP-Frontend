/**
 * 重音符号（组合附加符号）：写成 2 行的小图案，居中放在字母上方
 *  - 小写字母：放在第 0–1 行（x 高上方的空间里）；
 *  - 大写字母：放在第 -2 – -1 行（字母上方再加两行，rasterize 会自动扩高）；
 *  - below：放在基线下方（第 7–8 行），如 ç 的软音符、ę 的反尾形符。
 * 没列出的符号（如越南文 ư 的小角）会让整个字母退回系统字体绘制。
 */
const ACCENTS = {
  '\u0301': { rows: ['..#', '.#.'] }, // 尖音符 á é í ó ú
  '\u0300': { rows: ['#..', '.#.'] }, // 重音符 à è
  '\u0302': { rows: ['.#.', '#.#'] }, // 扬抑符 â ê ô
  '\u030C': { rows: ['#.#', '.#.'] }, // 抑扬符 č š ž
  '\u0303': { rows: ['.#.#', '#.#.'] }, // 波浪符 ã ñ õ
  '\u0308': { rows: ['.....', '.#.#.'], fit: true }, // 分音符 ä ö ü（两点按字宽放）
  '\u030A': { rows: ['.#.', '#.#'] }, // 上圆圈 å
  '\u0307': { rows: ['.', '#'] }, // 上点 ż
  '\u0327': { rows: ['.#.', '#..'], below: true }, // 软音符 ç
  '\u0328': { rows: ['#.', '.#'], below: true, right: true }, // 反尾形符 ą ę
}

function normalizeRows(rows) {
  const w = Math.max(...rows.map((r) => r.length))
  const out = rows.map((r) => r.padEnd(w, '.'))
  while (out.length < 9) out.push('.'.repeat(w))
  return out
}

const GLYPHS = new Map()
for (const [ch, rows] of Object.entries(RAW)) GLYPHS.set(ch, normalizeRows(rows))

/**
 * 作用：取一个字符的点阵。
 * 返回 { width, cells: [[x, y], ...] }（y 可以是负数 = 大写字母上方的重音），没有这个字就返回 null。
 */
const cache = new Map()
export function latinGlyph(ch) {
  if (cache.has(ch)) return cache.get(ch)
  let result = null
  const direct = GLYPHS.get(ch)
  if (direct) {
    result = toCells(direct)
  } else {
    // 带重音的字母：拆成"基础字母 + 组合符号"，例如 é → e + U+0301
    const [base, ...marks] = [...ch.normalize('NFD')]
    const g = GLYPHS.get(base)
    if (g && marks.length && marks.every((m) => ACCENTS[m])) {
      result = toCells(g)
      const upper = base !== base.toLowerCase()
      const w = result.width
      for (const m of marks) {
        const a = ACCENTS[m]
        const rows = a.fit ? fitDots(w) : a.rows
        const aw = rows[0].length
        const ox = a.right ? w - aw : Math.floor((w - aw) / 2)
        const oy = a.below ? 7 : upper ? -2 : 0
        // 小写 i / j 上面原本有点：加重音时把原来的点去掉
        if (!a.below && (base === 'i' || base === 'j')) result.cells = result.cells.filter(([, y]) => y > 1)
        rows.forEach((row, ry) => [...row].forEach((c, rx) => c === '#' && result.cells.push([ox + rx, oy + ry])))
      }
    }
  }
  cache.set(ch, result)
  return result
}

function toCells(rows) {
  const cells = []
  rows.forEach((row, y) => [...row].forEach((c, x) => c === '#' && cells.push([x, y])))
  return { width: rows[0].length, cells }
}

// 分音符的两个点：放在字宽的 1/4 与 3/4 处
function fitDots(w) {
  const row = Array(w).fill('.')
  row[Math.max(0, Math.round((w - 1) / 4))] = '#'
  row[Math.min(w - 1, Math.round(((w - 1) * 3) / 4))] = '#'
  return ['.'.repeat(w), row.join('')]
}

