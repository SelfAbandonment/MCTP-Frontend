/**
 * 作用：把字符转成像素坐标数组 [[x, y], ...]（以字形左上角为原点）
 * 原因：渲染层只关心"哪些格子要画"，统一在这里解析一次，避免各组件重复处理字符串。
 */
export function glyphCells(ch) {
  const rows = RAW[ch.toUpperCase()] || RAW[' ']
  const cells = []
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) if (row[x] === '#') cells.push([x, y])
  })
  return cells
}
